export const SETTING_KEYS = SETTINGS.map((s) => s.key);
const byKey = new Map(SETTINGS.map((s) => [s.key, s]));
export const getDef = (key: string): SettingDef | undefined => byKey.get(key);

export function defaults(): Record<string, unknown> {
  return Object.fromEntries(SETTINGS.map((s) => [s.key, s.default]));
}

export type Validation = { ok: true; value: unknown } | { ok: false; error: string };
export function validateSetting(key: string, value: unknown): Validation {
  const def = byKey.get(key);
  if (!def) return { ok: false, error: `unknown setting ${key}` };
  if (def.level === 'locked') return { ok: false, error: `${key} is locked (${def.decision})` };
  const r = def.schema.safeParse(value);
  return r.success
    ? { ok: true, value: r.data }
    : { ok: false, error: r.error.issues[0]?.message ?? 'invalid' };
}

/** Cross-field rules (docs/ADMIN.md section 3). Returns human-readable problems; empty = valid. */
export function crossCheck(v: Record<string, unknown>): string[] {
  const n = (k: string) => Number(v[k]);
  const out: string[] = [];
  if (n('cost.budget.plus.max') < n('cost.budget.plus.min'))
    out.push('Plus tavan, tabandan küçük olamaz');
  if (n('cost.budget.pro.max') < n('cost.budget.pro.min'))
    out.push('Pro tavan, tabandan küçük olamaz');
  if (n('cost.degrade.sonnetOffAt') >= n('cost.degrade.shortenAt'))
    out.push('Sonnet kapanma eşiği, kısaltma eşiğinden küçük olmalı');
  if (n('personal.estimateSlightKg') >= n('personal.estimateMuchKg'))
    out.push('“Biraz”, “çok”tan küçük olmalı');
  return out;
}

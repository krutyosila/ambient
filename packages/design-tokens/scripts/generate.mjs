// Extracts the 7 palettes (dark P, light L) from the design source of truth and writes src/generated.ts.
// Source: design/life-os-case-study.html. Run: pnpm tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, '../../../design/life-os-case-study.html'), 'utf8');

function grab(name) {
  const m = html.match(new RegExp(`(?:var |,)${name}=(\\[\\[[\\s\\S]*?\\]\\]);`));
  if (!m) throw new Error(`palette ${name} not found in prototype`);
  return Function(`"use strict";return (${m[1]})`)();
}
const toPalette = (row, dark) => ({
  name: row[0],
  bg: row[1],
  surface: row[2],
  accentRgb: row[3],
  accent: row[4],
  secondaryRgb: row[5],
  secondary: row[6],
  text: row[7],
  muted: row[8],
  ok: dark ? '#8fcf9f' : '#2f9e5f',
  warn: dark ? '#f2b45c' : '#c9860f',
});
// v2 contrast fix (docs/DESIGN.md 2.2): prototype light palettes miss 4.5:1 for accent/muted text.
// Mix the colour toward the text colour in 2% steps until it reaches 4.5:1 on the page background.
const hex2 = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const toHex = (c) => '#' + c.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');
const lin = (c) => ((c /= 255) <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (h) => {
  const [r, g, b] = hex2(h);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
};
const cr = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
};
function ensure(color, text, bg, min = 4.5) {
  let t = 0,
    out = color;
  while (cr(out, bg) < min && t < 1) {
    t += 0.02;
    const a = hex2(color),
      b = hex2(text);
    out = toHex(a.map((v, i) => v + (b[i] - v) * t));
  }
  return out;
}
const fix = (p) => {
  const accent = ensure(p.accent, p.text, p.bg),
    secondary = ensure(p.secondary, p.text, p.bg),
    muted = ensure(p.muted, p.text, p.bg);
  return {
    ...p,
    accent,
    accentRgb: hex2(accent).join(','),
    secondary,
    secondaryRgb: hex2(secondary).join(','),
    muted,
    v1: { accent: p.accent, secondary: p.secondary, muted: p.muted },
  };
};
const dark = grab('P').map((r) => fix(toPalette(r, true)));
const light = grab('L').map((r) => fix(toPalette(r, false)));
if (dark.length !== 7 || light.length !== 7) throw new Error('expected 7 palettes');

const out = `// GENERATED by scripts/generate.mjs from design/life-os-case-study.html. Do not edit.
export type Palette = {
  name: string;
  bg: string;
  surface: string;
  accentRgb: string;
  accent: string;
  secondaryRgb: string;
  secondary: string;
  text: string;
  muted: string;
  ok: string;
  warn: string;
  /** prototype (v1) values, kept where v2 adjusted them for contrast */
  v1: { accent: string; secondary: string; muted: string };
};
export const darkPalettes: Palette[] = ${JSON.stringify(dark, null, 2)};
export const lightPalettes: Palette[] = ${JSON.stringify(light, null, 2)};
`;
writeFileSync(join(here, '../src/generated.ts'), out);
console.log('tokens written:', dark.map((p) => p.name).join(', '));
